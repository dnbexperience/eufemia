import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import * as sass from 'sass'
import postcss from 'postcss'
import prettier from 'prettier'
import { sync as globSync } from 'globby'

const packageRoot = path.resolve(__dirname, '../../..')

export function getFontRevisions(
  readFont = (file: string) => fs.readFileSync(file)
) {
  const files: Record<string, string> = {}
  const faces = new Map<string, Set<string>>()
  const sources = globSync(['src/**/*.scss', '!src/**/__tests__/**'], {
    cwd: packageRoot,
    absolute: true,
  }).filter((file) => /@font-face/.test(fs.readFileSync(file, 'utf8')))
  for (const file of sources) {
    const root = postcss.parse(sass.compile(file).css)
    root.walkAtRules('font-face', (rule) => {
      const descriptors: Record<string, string> = {}
      rule.walkDecls((decl) => {
        descriptors[decl.prop] = decl.value
      })
      const family = descriptors['font-family'].replace(/['"]/g, '')
      descriptors.src = descriptors.src.replace(
        /url\(['"]?[^)'"]*\/assets\/fonts\/([^)'"]+)['"]?\)/g,
        (_, relativePath: string) => {
          const hash = crypto
            .createHash('sha256')
            .update(
              readFont(
                path.join(packageRoot, 'assets/fonts', relativePath)
              )
            )
            .digest('hex')
          files[relativePath] = hash
          return `url(${relativePath}:${hash})`
        }
      )
      const entries = faces.get(family) || new Set<string>()
      entries.add(JSON.stringify(descriptors))
      faces.set(family, entries)
    })
  }
  const families = Object.fromEntries(
    [...faces]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([family, entries]) => [
        family,
        `${family}-${crypto
          .createHash('sha256')
          .update([...entries].sort().join('\n'))
          .digest('hex')
          .slice(0, 16)}`,
      ])
  )
  return {
    families,
    files: Object.fromEntries(
      Object.entries(files).sort(([a], [b]) =>
        a < b ? -1 : a > b ? 1 : 0
      )
    ),
  }
}

export default async function makeFontRevisions() {
  const output = path.join(
    packageRoot,
    'src/plugins/postcss-isolated-style-scope/font-revisions.js'
  )
  fs.writeFileSync(
    output,
    await prettier.format(
      '// Generated by makeFontRevisions. Do not edit by hand.\nmodule.exports = ' +
        JSON.stringify(getFontRevisions(), null, 2) +
        '\n',
      { ...(await prettier.resolveConfig(output)), filepath: output }
    )
  )
}

if (require.main === module) {
  makeFontRevisions().catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
}
