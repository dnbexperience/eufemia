const transformModulesContent = async (content: string) => {
  const variables = parseCSSVariables(content)

  return (
    String(
      await prettier.format(
        `/** This file is auto generated by makePropertiesFile.ts */

export default ${JSON.stringify(variables, null, 2)}`,
        {
          filepath: 'file.js',
          semi: true,
          trailingComma: 'none',
          singleQuote: true,
        }
      )
    ).trim() + ' // prettier-ignore\n' // so manual changes not removes the semi
  )
}

const transformModulesContentCSS = async (content: string) => {
  // Convert --sb-* variables to Tailwind-compatible format
  const convertedVariables = convertVariablesToTailwindFormat(
    parseCSSVariables(content)
  )

  const cssContent = Object.entries(convertedVariables)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n')

  return (
    String(
      await prettier.format(
        `/* This file is auto generated by makePropertiesFile.ts */

/* stylelint-disable-next-line scss/at-rule-no-unknown */
@theme {
${cssContent}
}`,
        {
          filepath: 'file.css',
          parser: 'css',
          singleQuote: true,
          tabWidth: 2,
          useTabs: false,
        }
      )
    ).trim() + '\n'
  )
}

type RunFactoryOptions = {
  returnResult?: boolean
  glob?: string
}

export const runFactory = async ({
  returnResult = false,
  glob = './src/style/themes/*/properties-js.scss',
}: RunFactoryOptions = {}): Promise<string | undefined> => {
  log.start('> PrePublish: transforming style modules')

  const sassTransform = transformSass()
  const files = await globby([glob], { cwd: ROOT_DIR })

  for (const filePath of files) {
    const absolutePath = path.resolve(ROOT_DIR, filePath)
    const content = fs.readFileSync(absolutePath, 'utf-8')

    // Transform SCSS to CSS
    const cssContent = sassTransform(content, { path: absolutePath })

    // Generate JS properties file
    const jsResult = await transformModulesContent(cssContent)
    if (returnResult) {
      return jsResult
    }

    const parsed = path.parse(absolutePath)
    const jsDestPath = path.resolve(parsed.dir, 'properties.ts')
    fs.writeFileSync(jsDestPath, jsResult)

    // Generate CSS Tailwind properties file
    const cssResult = await transformModulesContentCSS(cssContent)

    const cssDestPath = path.resolve(parsed.dir, 'properties-tailwind.css')
    fs.writeFileSync(cssDestPath, cssResult)
  }

  return undefined
}

type FigmaAlias = {
  targetVariableName: string
  targetVariableSetId: string
  targetVariableSetName: string
}

type FigmaComposedColor = {
  colorArg: { type: 'alias'; alias: FigmaAlias }
  opacityArg: { type: 'number'; value: number }
}

type FigmaValueBase = {
  $type: string
  $value: unknown
  $extensions?: {
    'com.figma.aliasData'?: FigmaAlias
    'com.figma.composedColor'?: FigmaComposedColor
  }
}

type FigmaValueColor = {
  $type: 'color'
  $value: { alpha: number; hex: string }
} & FigmaValueBase

type FigmaValueString = {
  $type: 'string'
  $value: string
} & FigmaValueBase

type FigmaValueNumber = {
  $type: 'number'
  $value: number
} & FigmaValueBase

type FigmaValue = FigmaValueColor | FigmaValueNumber | FigmaValueString

type FigmaGroup = {
  $root?: FigmaValue
} & FigmaExport

type FigmaNode = FigmaValue | FigmaGroup

type FigmaExport = {
  [x: string]: FigmaNode
}

type FigmaSetId =
  (typeof TOKEN_SETS)[keyof typeof TOKEN_SETS]['targetVariableSetId']

// Types for converted Figma export files for internal use in token generation
type TokenList = TokenItem[]

type TokenItem = {
  figmaPath: string[]
  figmaSetId: FigmaSetId
} & FigmaValue

/** Previous declarations of tokens whose new Figma value is held back */
type HeldBackDeclarations = Map<
  string,
  { value: string; fallback?: string }
>

export const transformFigmaAlias = (alias: FigmaAlias) => {
  const figmaAliasName = alias.targetVariableName
  const figmaAliasSetId = alias.targetVariableSetId

  if (figmaAliasSetId === TOKEN_SETS.colors.targetVariableSetId) {
    const path = figmaAliasName.split('/')

    let knownPrefix = false
    Object.values(foundationPrefixMap).forEach((prefix) => {
      // TODO: perhaps we should be even more strict and ensure that the prefix is from the correct theme
      if (path[0] === prefix.figma) {
        knownPrefix = true
      }
    })

    if (!knownPrefix) {
      const errorMessage = `Unsupported theme prefix: "${path[0]}" for alias "${figmaAliasName}"`
      log.fail(errorMessage)
      throw new Error(errorMessage)
    }

    let knownCollection = false
    Object.values(TOKEN_SETS).forEach((tokenSet) => {
      if (figmaAliasSetId === tokenSet.targetVariableSetId) {
        knownCollection = true
      }
    })

    if (!knownCollection) {
      const errorMessage = `Unsupported variable set id: "${figmaAliasSetId}" for alias "${figmaAliasName}"`
      log.fail(errorMessage)
      throw new Error(errorMessage)
    }

    return `var(${transformNamespace()}${transformFigmaPath({ figmaPath: path, figmaSetId: figmaAliasSetId })})` // Including transform namespace as we might want to be able to apply that in the future
  }

  const errorMessage = `Unsupported variable set id: "${figmaAliasSetId}" for alias "${figmaAliasName}"`
  log.fail(errorMessage)
  throw new Error(errorMessage)
}

const hexAsRgb = (hex: string) => {
  if (hex.length !== 7) {
    throw new Error(`Can't parse hex string: ${hex}`)
  }
  return `${parseInt(hex.substring(1, 3), 16)} ${parseInt(
    hex.substring(3, 5),
    16
  )} ${parseInt(hex.substring(5, 7), 16)}`
}

const compressHex = (hex: string) => {
  if (!/^#[0-9a-fA-F]{6}$/.test(hex)) {
    return hex
  }

  const r1 = hex[1]
  const r2 = hex[2]
  const g1 = hex[3]
  const g2 = hex[4]
  const b1 = hex[5]
  const b2 = hex[6]

  if (
    r1.toLowerCase() === r2.toLowerCase() &&
    g1.toLowerCase() === g2.toLowerCase() &&
    b1.toLowerCase() === b2.toLowerCase()
  ) {
    return `#${r1}${g1}${b1}`.toLowerCase()
  }

  return hex.toLowerCase()
}

const alphaAsPercent = (alpha: number) => {
  const value = parseFloat((alpha * 100).toFixed(2))
  return `${value}%`
}

const shouldTransformFigmaAlias = (value: FigmaValue) => {
  const alias = value?.$extensions?.['com.figma.aliasData']

  if (alias) {
    switch (alias.targetVariableSetId) {
      case TOKEN_SETS.colors.targetVariableSetId:
        return true
      case TOKEN_SETS.sizes.targetVariableSetId:
      case TOKEN_SETS.typography.targetVariableSetId: {
        // Numeric foundation aliases use the exported value directly.
        if (value.$type !== 'number') {
          const errorMessage = `Unexpected type: ${value.$type} in variable set id "${alias.targetVariableSetId}" (name: "${alias.targetVariableSetName}")`
          log.fail(errorMessage)
          throw new Error(errorMessage)
        }
        return false
      }
    }

    // Any unknown aliases should throw error. The set is matched by id, so
    // a known name can still fail when the collection is recreated in Figma.
    throw new Error(
      `Unsupported variable set id: "${alias.targetVariableSetId}" (name: "${alias.targetVariableSetName}") for alias "${alias.targetVariableName}"`
    )
  }

  return false
}

export const transformFigmaValue = (value: FigmaValue) => {
  if (shouldTransformFigmaAlias(value)) {
    return transformFigmaAlias(
      value.$extensions?.['com.figma.aliasData'] as FigmaAlias
    )
  }

  const composed = getComposedColor(value)
  if (composed) {
    return `color-mix(in srgb, ${transformFigmaAlias(
      composed.colorArg.alias
    )} ${composed.opacityArg.value}%, transparent)`
  }

  return transformFigmaRawValue(value)
}

const getComposedColor = (value: FigmaValue) => {
  const composed = value.$extensions?.['com.figma.composedColor']

  return composed?.colorArg?.type === 'alias' &&
    composed.opacityArg?.type === 'number'
    ? composed
    : undefined
}

const COLOR_MIX_FALLBACK_CONDITION =
  '@supports not (color: color-mix(in srgb, red, red))'

/** Literal values of the composed colors, for browsers without `color-mix()` */
export const generateColorMixFallback = (
  tokenList: TokenList,
  selector: string,
  namespace?: string
) => {
  const declarations = generateColorMixFallbackDeclarations(
    tokenList,
    namespace
  )

  return wrapColorMixFallback(declarations, selector)
}

const generateColorMixFallbackDeclarations = (
  tokenList: TokenList,
  namespace?: string
) =>
  generateCSSVariablesFromTokenList(
    tokenList
      .filter((token) => getComposedColor(token))
      .map((token) => ({ ...token, $extensions: undefined })),
    namespace
  )

const wrapColorMixFallback = (declarations: string, selector: string) =>
  declarations
    ? `${COLOR_MIX_FALLBACK_CONDITION} {\n${selector} {\n${declarations}}\n}\n`
    : ''

const replaceHeldBackDeclarations = (
  declarations: string,
  heldBack: HeldBackDeclarations,
  pick: (declaration: { value: string; fallback?: string }) => string
) => {
  const remaining = new Map(heldBack)
  const lines = declarations
    .split('\n')
    .filter(Boolean)
    .flatMap((line) => {
      const name = line.match(CSS_VARIABLE_DECLARATION_REGEX)?.[1]

      if (!heldBack.has(name)) {
        return [line]
      }

      remaining.delete(name)
      const value = pick(heldBack.get(name))

      return value ? [`${name}: ${value};`] : []
    })

  remaining.forEach((declaration, name) => {
    const value = pick(declaration)

    if (value) {
      lines.push(`${name}: ${value};`)
    }
  })

  return lines.length ? lines.join('\n') + '\n' : ''
}

/** Declarations of a generated SCSS file, split into the main block and the `color-mix()` fallback */
const parseGeneratedDeclarations = (content: string) => {
  const fallbackIndex = content.indexOf(COLOR_MIX_FALLBACK_CONDITION)
  const parse = (css: string) =>
    new Map(
      Array.from(css.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)).map(
        ([, name, value]) => [
          name,
          value
            .replace(/\s+/g, ' ')
            .replace(/\(\s/g, '(')
            .replace(/\s\)/g, ')')
            .trim(),
        ]
      )
    )

  return {
    main: parse(
      fallbackIndex === -1 ? content : content.slice(0, fallbackIndex)
    ),
    fallback: parse(
      fallbackIndex === -1 ? '' : content.slice(fallbackIndex)
    ),
  }
}

const transformFigmaRawValue = (value: FigmaValue) => {
  if (value.$type === 'number') {
    return transformNumberValue(value.$value as number)
  }

  if (value.$type === 'color') {
    const alpha = value.$value.alpha
    const hex = value.$value.hex

    return alpha === 1
      ? compressHex(hex)
      : `rgba(${hexAsRgb(hex)} / ${alphaAsPercent(alpha)})`
  } else {
    throw new Error(`Unsupported $type: ${value.$type}`)
  }
}
/**
 * Returns the path part of the CSS variable based on the figmaPath of a token item.
 *
 * `[ "Color", "Background", "Primary" ]` -> `"color-background-primary"`
 */
export const transformFigmaPath = (
  value: Pick<TokenItem, 'figmaPath' | 'figmaSetId'>
) => {
  const path = value.figmaPath

  const unsupportedCharacters = []

  const cleanPath = path.filter(Boolean)

  // Transforms for names
  if (value.figmaSetId === TOKEN_SETS.colors.targetVariableSetId) {
    Object.values(foundationPrefixMap).forEach((prefix) => {
      // TODO: perhaps we should be even more strict and ensure that the prefix is from the correct theme
      if (cleanPath[0] === prefix.figma) {
        cleanPath[0] = prefix.css
      }
    })
  }

  // Transforms for valid formatting
  const transformedPath = cleanPath
    .map((group) => {
      unsupportedCharacters.push(...(group.match(/[^a-zA-Z-0-9]/g) ?? []))
      return group.toLowerCase()
    })
    .join(TOKEN_GROUP_SEPARATOR)

  if (unsupportedCharacters.length > 0) {
    const errorMessage = `Unsupported characters [ '${unsupportedCharacters.join(
      "', '"
    )}' ] in variable: "${cleanPath.join('/')}"`
    log.fail(errorMessage)
    throw new Error(errorMessage)
  }

  return transformedPath
}

export const transformNamespace = (namespace?: string) =>
  TOKEN_CSS_PREFIX + (namespace ? namespace + TOKEN_GROUP_SEPARATOR : '')

export const extractReferencedCssVariables = (content: string) => {
  const variables = new Set<string>()
  let match: RegExpExecArray | null
  const regex = new RegExp(CSS_VARIABLE_REFERENCE_REGEX)

  while ((match = regex.exec(content)) !== null) {
    const variableName = match[1]

    if (variableName) {
      variables.add(variableName)
    }
  }

  return variables
}

const keepOnlyReferencedVariableDeclarations = (
  content: string,
  referencedVariables: Set<string>
) => {
  return content
    .split('\n')
    .filter((line) => {
      const variableDeclarationMatch = line.match(
        CSS_VARIABLE_DECLARATION_REGEX
      )

      if (!variableDeclarationMatch) {
        return true
      }

      const variableName = variableDeclarationMatch[1]

      return referencedVariables.has(variableName)
    })
    .join('\n')
}

const shouldGenerateCSSVariable = (value: TokenItem) =>
  value.$type !== 'string' && value.figmaPath[0] !== 'font'

/** Generates CSS variables as a SCSS string from a token list */
export const generateCSSVariablesFromTokenList = (
  /** An exported figma collection converted to a token list */
  tokenList: TokenList,
  /** string placed first in the css variable: `--namespace-color-blue-500` */
  namespace?: string
) => {
  let returnValue = ''

  tokenList.forEach((value) => {
    try {
      if (shouldGenerateCSSVariable(value)) {
        const valuePart = transformFigmaValue(value)

        if (valuePart) {
          const namespacePart = transformNamespace(namespace)
          const pathPart = transformFigmaPath(value)

          returnValue += `${namespacePart}${pathPart}: ${valuePart};\n`
        }
      }
    } catch (e) {
      const err = e as Error & {
        recursionContext?: {
          path: string[]
          namespace: string
          value: unknown
        }
      }
      if (!err.recursionContext) {
        err.recursionContext = {
          path: value.figmaPath,
          namespace,
          value,
        }
      }
      throw err
    }
  })

  return returnValue
}

const makeDesignTokenTailwindCSS = async (
  /** Root path to the generated tokens.scss file */
  tokensScssPath: string,
  /** Root path for the generated Tailwind CSS file */
  outputPath: string,
  /** prefix to strip from variable names (e.g. 'token') */
  prefix: string
) => {
  try {
    const content = await promises.readFile(tokensScssPath, 'utf-8')

    // Extract complete CSS declarations by selector block (which may span multiple lines)
    const prefixPattern = `--${prefix}-`
    const declarationsBySelector = new Map<string, string[]>()
    const nativeDeclarationsBySelector = new Map<string, string[]>()
    const lines = content.split('\n')
    let currentDeclaration = ''
    let collecting = false
    let currentSelector: string | null = null

    let pendingSelectorLines: string[] = []
    let skippedBlockDepth = 0

    for (const line of lines) {
      const trimmed = line.trim()

      // Tailwind v4 requires color-mix() support, so it needs no fallback
      if (
        skippedBlockDepth > 0 ||
        trimmed.startsWith(COLOR_MIX_FALLBACK_CONDITION)
      ) {
        skippedBlockDepth +=
          trimmed.split('{').length - trimmed.split('}').length
        continue
      }

      if (!collecting && trimmed.endsWith('{')) {
        currentSelector = [...pendingSelectorLines, trimmed.slice(0, -1)]
          .map((s) => s.trim())
          .filter(Boolean)
          .join(' ')
        pendingSelectorLines = []
        continue
      }

      // Accumulate multi-line selectors (e.g. `:root,\n.foo {`)
      if (
        !collecting &&
        !currentSelector &&
        trimmed &&
        !trimmed.startsWith('/*') &&
        !trimmed.startsWith('--')
      ) {
        pendingSelectorLines.push(trimmed)
        continue
      }

      if (!collecting && trimmed === '}') {
        currentSelector = null
        continue
      }

      if (
        !collecting &&
        currentSelector &&
        trimmed.startsWith('color-scheme:')
      ) {
        const selectorDeclarations =
          nativeDeclarationsBySelector.get(currentSelector) ?? []
        selectorDeclarations.push(`  ${trimmed}`)
        nativeDeclarationsBySelector.set(
          currentSelector,
          selectorDeclarations
        )
        continue
      }

      if (
        !collecting &&
        currentSelector &&
        trimmed.startsWith(prefixPattern)
      ) {
        collecting = true
        currentDeclaration = trimmed
      } else if (collecting && currentSelector) {
        currentDeclaration += '\n' + line
      }

      if (
        collecting &&
        currentSelector &&
        currentDeclaration.includes(';')
      ) {
        // Strip the prefix from the variable name
        const strippedDeclaration = currentDeclaration.replace(
          new RegExp(`${prefixPattern}`),
          '--'
        )
        const selectorDeclarations =
          declarationsBySelector.get(currentSelector) ?? []
        selectorDeclarations.push(`  ${strippedDeclaration.trim()}`)
        declarationsBySelector.set(currentSelector, selectorDeclarations)
        collecting = false
        currentDeclaration = ''
      }
    }

    const rootEntry = Array.from(declarationsBySelector.entries()).find(
      ([selector]) => selector.includes(':root')
    )
    const rootSelector = rootEntry?.[0]
    const rootDeclarations = rootEntry?.[1] ?? []
    const themeContent = rootDeclarations.join('\n')
    const nativeRootDeclarations = rootSelector
      ? (nativeDeclarationsBySelector.get(rootSelector) ?? [])
      : []
    const nativeRootBlock = nativeRootDeclarations.length
      ? `${rootSelector} {\n${nativeRootDeclarations.join('\n')}\n}\n`
      : ''

    const scopedSelectors = Array.from(declarationsBySelector.entries())
      .filter(([selector]) => selector !== rootSelector)
      .map(([selector, declarations]) => {
        const nativeDeclarations =
          nativeDeclarationsBySelector.get(selector) ?? []
        const combinedDeclarations = [
          ...nativeDeclarations,
          nativeDeclarations.length && declarations.length ? '' : null,
          ...declarations,
        ].filter((declaration) => declaration !== null)
        return `${selector} {\n${combinedDeclarations.join('\n')}\n}`
      })
      .join('\n\n')

    const themeBlock = themeContent
      ? `/* stylelint-disable-next-line scss/at-rule-no-unknown */
@theme {
${themeContent}
}
`
      : ''

    const tailwindContent = `/* This file is auto generated by makePropertiesFile.ts */

/* stylelint-disable eufemia/token-name-policy */
${themeBlock}${nativeRootBlock}${scopedSelectors ? `${scopedSelectors}\n` : ''}
`

    const prettierResult =
      String(
        await prettier.format(tailwindContent, {
          filepath: 'file.css',
          ...prettierrc,
        })
      ).trim() + '\n'

    await promises.writeFile(outputPath, prettierResult)

    log.info(`Generated Tailwind CSS file: ${outputPath}`)
  } catch (e) {
    log.fail(`Failed to generate Tailwind CSS file: ${outputPath}`)
    throw e
  }
}

const makeDesignTokenSCSS = async ({
  inputPath,
  outputPath,
  figmaSetId,
  namespace,
  scopeSelector = ':root',
  appendToFile = false,
  referencedVariables,
  colorScheme,
  heldBack,
}: {
  /** Root path to Figma JSON export file */
  inputPath: string
  /** Root path for the generated SCSS file */
  outputPath: string
  /** id of the Figma collection */
  figmaSetId: FigmaSetId
  /** prefix that is added to the start of the css variable name */
  namespace?: string
  /** selector receiving generated variables */
  scopeSelector?: string
  /** append generated content to existing file */
  appendToFile?: boolean
  referencedVariables?: Set<string>
  colorScheme?: 'light' | 'dark'
  heldBack?: HeldBackDeclarations
}) => {
  try {
    const tokenList = convertToTokenList(
      JSON.parse(fs.readFileSync(path.resolve(inputPath), 'utf-8')),
      figmaSetId
    )

    // When scoping to :root, also add .eufemia-theme__color-scheme--light
    // so that light tokens can override dark tokens in nested contexts.
    const combinedSelector =
      scopeSelector === ':root'
        ? ':root,\n.eufemia-theme__color-scheme--light'
        : scopeSelector

    let scssContent = `${combinedSelector} {\n`

    if (colorScheme) {
      scssContent += `color-scheme: ${colorScheme};\n`
    }

    let declarations = generateCSSVariablesFromTokenList(
      tokenList,
      namespace
    )
    let fallbackDeclarations = generateColorMixFallbackDeclarations(
      tokenList,
      namespace
    )

    if (heldBack) {
      declarations = replaceHeldBackDeclarations(
        declarations,
        heldBack,
        ({ value }) => value
      )
      fallbackDeclarations = replaceHeldBackDeclarations(
        fallbackDeclarations,
        heldBack,
        ({ fallback }) => fallback
      )
    }

    scssContent += declarations
    scssContent += '}\n'
    scssContent += wrapColorMixFallback(
      fallbackDeclarations,
      combinedSelector
    )

    if (referencedVariables) {
      scssContent = keepOnlyReferencedVariableDeclarations(
        scssContent,
        referencedVariables
      )
    }

    const formattedScssContent = String(
      await prettier.format(scssContent, {
        filepath: '*.scss',
        ...prettierrc,
      })
    )

    const outputScssContent = appendToFile
      ? `\n${formattedScssContent}`
      : `/* This file is auto generated by makePropertiesFile.ts */\n\n${formattedScssContent}`

    const stylelintResult = await stylelint.lint({
      code: outputScssContent,
      fix: true,
      // Babel compiles this script to CommonJS, so it can only use the CommonJS API
      quietDeprecationWarnings: true,
    })

    // `code` holds the autofixed output; `output` is deprecated in stylelint 16
    const fixedContent = stylelintResult.code ?? outputScssContent

    if (appendToFile) {
      await promises.appendFile(outputPath, fixedContent)
    } else {
      await promises.writeFile(outputPath, fixedContent)
    }

    log.info(`Generated SCSS file: ${outputPath}`)
  } catch (e) {
    log.fail(`Failed to generate SCSS file: ${outputPath}`)
    throw e
  }
}

export const convertToTokenList = (
  node: FigmaNode,
  figmaSetId: FigmaSetId
) => {
  const convertRecursive = (node: FigmaNode, figmaPath: string[] = []) => {
    let list: TokenList = []

    if (typeof node !== 'object' || node === null) {
      const nodePath = figmaPath.filter(Boolean).join('/') || '<root>'
      const errorMessage = `Invalid Figma token node at "${nodePath}": expected an object`
      log.fail(errorMessage)
      throw new Error(errorMessage)
    }

    if ('$type' in node) {
      list.push({ figmaPath, figmaSetId, ...(node as FigmaValue) })
    } else {
      Object.entries(node).forEach(([key, value]) => {
        if (key !== '$extensions') {
          list = list.concat(
            convertRecursive(value, [
              ...figmaPath,
              key === '$root' ? '' : key,
            ])
          )
        }
      })
    }

    return list
  }

  const tokenList = convertRecursive(node)

  if (tokenList.length === 0) {
    const errorMessage = 'Invalid Figma export: no tokens found'
    log.fail(errorMessage)
    throw new Error(errorMessage)
  }

  return tokenList
}

