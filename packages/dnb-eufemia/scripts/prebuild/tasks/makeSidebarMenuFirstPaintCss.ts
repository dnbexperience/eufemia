import fs from 'node:fs/promises'
import path from 'node:path'
import * as sass from 'sass'
import prettier from 'prettier'

const packageRoot = path.resolve(__dirname, '../../..')
const styleRoot = path.join(
  packageRoot,
  'src/extensions/sidebar-menu/style'
)
const outputPath = path.join(
  packageRoot,
  'src/extensions/sidebar-menu/SidebarMenuFirstPaintCss.ts'
)

export async function createSidebarMenuFirstPaintCss() {
  const compile = (name: 'drawer' | 'compact') =>
    sass.compileString(
      '@use "sidebar-menu-first-paint" as first-paint; @include first-paint.' +
        name +
        ';',
      { loadPaths: [styleRoot], style: 'compressed', charset: false }
    ).css
  const config = JSON.parse(
    await fs.readFile(path.join(packageRoot, '.prettierrc'), 'utf8')
  )
  return prettier.format(
    [
      '// Generated by makeSidebarMenuFirstPaintCss.ts. Edit the shared SCSS mixins, not this file.',
      'export const drawerFirstPaintCss = ' +
        JSON.stringify(compile('drawer')),
      'export const compactFirstPaintCss = ' +
        JSON.stringify(compile('compact')),
    ].join('\n'),
    { ...config, parser: 'typescript' }
  )
}

export default async function makeSidebarMenuFirstPaintCss() {
  await fs.writeFile(outputPath, await createSidebarMenuFirstPaintCss())
}

if (typeof require !== 'undefined' && require.main === module) {
  makeSidebarMenuFirstPaintCss().catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
}
