import { checkFlagIconsUpdate } from '../checkFlagIconsUpdate.mjs'

const lock = (
  version: string,
  extra = ''
) => `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 10
  cacheKey: 10

"@dnb/eufemia@workspace:*, @dnb/eufemia@workspace:packages/dnb-eufemia":
  version: 0.0.0-use.local
  resolution: "@dnb/eufemia@workspace:packages/dnb-eufemia"
  dependencies:
    flag-icons: "npm:${version}"
    react: "npm:19.0.0"${extra}
  languageName: unknown
  linkType: soft

"flag-icons@npm:${version}":
  version: ${version}
  resolution: "flag-icons@npm:${version}"
  checksum: 10/${version.replaceAll('.', '')}
  languageName: node
  linkType: hard

"react@npm:19.0.0":
  version: 19.0.0
  resolution: "react@npm:19.0.0"
  checksum: 10/abc
  languageName: node
  linkType: hard
`

const manifest = (version: string, extra: Record<string, unknown> = {}) =>
  JSON.stringify({
    name: '@dnb/eufemia',
    scripts: { build: 'babel' },
    devDependencies: { 'flag-icons': version, react: '19.0.0' },
    ...extra,
  })

describe('checkFlagIconsUpdate', () => {
  it('accepts an update of the flag-icons version only', () => {
    expect(
      checkFlagIconsUpdate({
        beforeLock: lock('7.5.0'),
        afterLock: lock('7.6.0'),
        beforeManifest: manifest('7.5.0'),
        afterManifest: manifest('7.6.0'),
      })
    ).toEqual([])
  })

  it('reports a lockfile entry of another package that changed', () => {
    expect(
      checkFlagIconsUpdate({
        beforeLock: lock('7.5.0'),
        afterLock: lock('7.6.0').replace(
          'checksum: 10/abc',
          'checksum: 10/evil'
        ),
        beforeManifest: manifest('7.5.0'),
        afterManifest: manifest('7.6.0'),
      })
    ).toEqual(['yarn.lock: "react@npm:19.0.0" changed'])
  })

  it('reports a new lockfile entry of another package', () => {
    expect(
      checkFlagIconsUpdate({
        beforeLock: lock('7.5.0'),
        afterLock: `${lock('7.6.0')}
"evil@npm:1.0.0":
  version: 1.0.0
  resolution: "evil@npm:1.0.0"
`,
        beforeManifest: manifest('7.5.0'),
        afterManifest: manifest('7.6.0'),
      })
    ).toEqual(['yarn.lock: "evil@npm:1.0.0" changed'])
  })

  it('reports a workspace dependency other than flag-icons that changed', () => {
    expect(
      checkFlagIconsUpdate({
        beforeLock: lock('7.5.0'),
        afterLock: lock('7.6.0', '\n    evil: "npm:1.0.0"'),
        beforeManifest: manifest('7.5.0'),
        afterManifest: manifest('7.6.0'),
      })
    ).toEqual([
      'yarn.lock: "@dnb/eufemia@workspace:*, @dnb/eufemia@workspace:packages/dnb-eufemia" changed',
    ])
  })

  it('reports a package.json change other than the flag-icons version', () => {
    expect(
      checkFlagIconsUpdate({
        beforeLock: lock('7.5.0'),
        afterLock: lock('7.6.0'),
        beforeManifest: manifest('7.5.0'),
        afterManifest: manifest('7.6.0', {
          scripts: { build: 'babel', postinstall: 'node evil.js' },
        }),
      })
    ).toEqual([
      'packages/dnb-eufemia/package.json: changes more than the flag-icons version',
    ])
  })
})
