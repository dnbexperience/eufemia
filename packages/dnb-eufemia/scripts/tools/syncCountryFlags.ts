/**
 * Copies the square (1x1) flags from the flag-icons package into our assets
 * and generates the CountryFlag icon styles.
 *
 * Run: yarn flags:sync
 */

import fs from 'fs'
import path from 'path'

const packageRoot = path.resolve(__dirname, '../..')

export const flagsDir = path.resolve(packageRoot, 'assets/flags')
export const stylesFile = path.resolve(
  packageRoot,
  'src/components/country-flag/style/dnb-country-flag-icons.scss'
)

export function getFlagIconsSource() {
  const dir = path.dirname(require.resolve('flag-icons/package.json'))
  const { version } = JSON.parse(
    fs.readFileSync(path.join(dir, 'package.json'), 'utf-8')
  )
  const squareDir = path.join(dir, 'flags/1x1')

  const flags = fs
    .readdirSync(squareDir)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => path.basename(file, '.svg'))
    .sort()

  // Keep "xx" first, as it is used as the fallback flag
  flags.sort((a, b) => Number(b === 'xx') - Number(a === 'xx'))

  return { dir, version, squareDir, flags }
}

export function makeFlagStyles(version: string, flags: Array<string>) {
  const header = `/*
* Import all flag icons (SVG) via CSS
*
* License: MIT
* Repo: https://github.com/lipis/flag-icons
* Version: ${version}
*
* This file is generated by "yarn flags:sync". Do not edit it manually.
* To update the flags, change the "flag-icons" version in package.json and run the script.
*
* We only use the 1x1 flags, so we include them in our assets folder instead of depending on the flag-icons package.
* This lowers the overall footprint of the package and the amount of work the compilers needs to do.
* Some bundlers also rewrote the path 'flag-icons/flags/1x1/xx.svg' to the invalid path './flag-icons/flags/1x1/xx.svg'.
*/
`

  const rules = flags.map(
    (flag) => `
.fi-${flag}.fis {
  background-image: url('../../../../assets/flags/1x1/${flag}.svg');
}
`
  )

  return header + rules.join('')
}

export function syncCountryFlags() {
  const { dir, version, squareDir, flags } = getFlagIconsSource()
  const targetDir = path.join(flagsDir, '1x1')

  fs.rmSync(targetDir, { recursive: true, force: true })
  fs.mkdirSync(targetDir, { recursive: true })

  for (const flag of flags) {
    fs.copyFileSync(
      path.join(squareDir, `${flag}.svg`),
      path.join(targetDir, `${flag}.svg`)
    )
  }

  fs.writeFileSync(
    path.join(flagsDir, 'LICENSE'),
    'All the SVG files are copied from https://github.com/lipis/flag-icons/tree/main/flags/1x1\n\n' +
      fs.readFileSync(path.join(dir, 'LICENSE'), 'utf-8')
  )
  fs.writeFileSync(stylesFile, makeFlagStyles(version, flags))

  console.log(`Synced ${flags.length} flags from flag-icons v${version}`)
}

if (require.main === module) {
  syncCountryFlags()
}
